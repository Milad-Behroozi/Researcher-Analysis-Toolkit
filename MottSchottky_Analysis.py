    def build_capacitance(self, lf: LoadedFile) -> Tuple[np.ndarray, str]:
        """
        Returns (C array, note)
        """
        df = lf.df_raw
        if lf.E_meas is None:
            raise RuntimeError("Columns not loaded yet. Click 'Load Selected File Columns' first.")

        # Case A: direct capacitance
        if lf.cols.get("C"):
            C = coerce_numeric(df[lf.cols["C"]])
            return C, "C(V) from file"

        # Case B: EIS from Z' & Z''
        if lf.cols.get("Zre") and lf.cols.get("Zim"):
            Zre = coerce_numeric(df[lf.cols["Zre"]])
            Zim = coerce_numeric(df[lf.cols["Zim"]])

            # Frequency: from file or from guided input
            freq_col = lf.cols.get("Freq")
            if freq_col:
                f_all = coerce_numeric(df[freq_col])
                # If frequency varies, choose a single frequency (median) for now
                f_valid = f_all[np.isfinite(f_all) & (f_all > 0)]
                if f_valid.size == 0:
                    raise RuntimeError("Frequency column exists but has no valid positive values.")
                # Choose median frequency; user can adjust with the AC frequency box if desired
                freq = float(np.median(f_valid))
                note = f"Frequency from file (median ~ {freq:g} Hz)"
            else:
                if not self.chk_need_freq.isChecked():
                    raise RuntimeError("Frequency needed for EIS→C, but 'Use/require frequency' is disabled.")
                freq = float(self.sp_freq.value())
                if freq <= 0:
                    raise RuntimeError("Please enter a valid AC frequency (Hz).")
                note = f"Frequency from guided input ({freq:g} Hz)"

            omega = 2 * np.pi * freq

            method = self.cmb_cmethod.currentIndex()
            if method == 0:
                C = capacitance_from_eis(Zre, Zim, freq)
            else:
                # Simple approximation: C ≈ -1/(ω Z'')
                # In capacitive region Z'' is typically negative -> C positive
                Zim_safe = np.where(np.abs(Zim) < 1e-30, np.nan, Zim)
                C = -1.0 / (omega * Zim_safe)

            return C, f"EIS→C ({note})"

        raise RuntimeError("No capacitance column and insufficient EIS columns (need Z' and Z\").")

    
