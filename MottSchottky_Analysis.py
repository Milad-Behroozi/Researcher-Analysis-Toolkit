    # ------------- Quick plotting (no fitting) -------------
    def _prepare_ms_data(self, lf: LoadedFile):
        """Return cleaned/sorted arrays for plotting Mott–Schottky without fitting.
        Returns (E_plot, Y_scaled, exp, unit, phase_abs_deg or None).
        """
        df = lf.df_raw
        if lf.E_meas is None:
            if lf.cols.get("E") is None:
                raise RuntimeError("Potential column not detected. Select it manually.")
            lf.E_meas = coerce_numeric(df[lf.cols["E"]])

        C, noteC = self.build_capacitance(lf)

        # Align
        E = lf.E_meas
        P = None
        if lf.cols.get("Phase"):
            P = coerce_numeric(df[lf.cols["Phase"]])
        if E.shape != C.shape:
            n = min(len(E), len(C))
            E, C = E[:n], C[:n]
            if P is not None:
                P = P[:n]

        mask = np.isfinite(E) & np.isfinite(C)
        if P is not None:
            mask = mask & np.isfinite(P)
        E = E[mask]
        C = C[mask]
        if P is not None:
            P = P[mask]

        C = np.where(C <= 0, np.nan, C)
        mask = np.isfinite(C)
        E, C = E[mask], C[mask]
        if P is not None:
            P = P[mask]

        order = np.argsort(E)
        E, C = E[order], C[order]
        if P is not None:
            P = P[order]

        if E.size < 2:
            raise RuntimeError("Too few valid points to plot.")

        display_offset = float(self.sp_disp_offset.value())
        E_plot = self.potential_for_output_scale(E) + display_offset

        use_area = self.chk_area.isChecked()
        area = float(self.sp_area.value())
        if use_area:
            if area <= 0:
                raise RuntimeError("Area must be positive.")
            C_area = C / area
            Y = 1.0 / (C_area ** 2)
            unit = "F$^{-2}$ cm$^4$"
        else:
            Y = 1.0 / (C ** 2)
            unit = "F$^{-2}$ (raw)"

        exp = choose_scale_exponent(Y)
        Y_scaled = Y / (10 ** exp) if exp != 0 else Y

        phase_abs = None
        if P is not None:
            phase_abs = np.abs(P)

        lf.note = (lf.note + " | " if lf.note else "") + noteC
        lf.C = C
        lf.Y_ms = Y
        lf.scale_exp = exp
        return E_plot, Y_scaled, exp, unit, phase_abs

