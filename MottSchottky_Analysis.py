def read_table_any_delim(path: str) -> pd.DataFrame:
    # Try common separators; fall back to python engine with sniff.
    seps = ["\t", ",", ";", "|"]
    last_err = None
    for sep in seps:
        try:
            df = pd.read_csv(path, sep=sep, engine="python")
            if df.shape[1] >= 2:
                return df
        except Exception as e:
            last_err = e
    # Fallback: let pandas sniff
    try:
        df = pd.read_csv(path, sep=None, engine="python")
        return df
    except Exception as e:
        raise RuntimeError(f"Could not read file: {path}\nLast error: {last_err}\nSniff error: {e}")


def normalize_colname(s: str) -> str:
    s = str(s).strip()
    s = s.replace("Ω", "ohm")
    s = re.sub(r"\s+", "", s)
    s = s.replace("'", "prime").replace('"', "dprime")
    return s.lower()


def auto_detect_columns(df: pd.DataFrame) -> Dict[str, Optional[str]]:
    """
    Returns mapping keys:
      E, C, Zre, Zim, Zmag, Phase, Freq
    """
    cols = list(df.columns)
    norm = {c: normalize_colname(c) for c in cols}

    def pick(patterns):
        for c in cols:
            n = norm[c]
            for p in patterns:
                if re.search(p, n):
                    return c
        return None

    # Potential column
    E = pick([
        r"^potential", r"^ewe", r"^e$", r"e/v", r"potential/v", r"voltage", r"^v$",
        r"^e\(v\)", r"^potential\(v\)"
    ])

    # Capacitance column
    C = pick([
        r"^capacitance", r"^c$", r"^csc", r"^c_dl", r"^cdl", r"^carea", r"^c\(f\)"
    ])

    # Frequency
    Freq = pick([r"^freq", r"^frequency", r"hz$"])

    # Impedance components
    Zre = pick([r"zprime", r"^zre", r"re\(z\)", r"^zreal", r"z'/", r"^z\+?re"])
    Zim = pick([r"zdprime", r"^zim", r"im\(z\)", r"^zimag", r"z\"/", r"^z\+?im"])
    Zmag = pick([r"^\|z\|", r"^z/ohm$", r"^z$", r"^mag", r"^absz"])

    Phase = pick([r"^phase", r"deg$", r"^phi"])

    return {"E": E, "C": C, "Freq": Freq, "Zre": Zre, "Zim": Zim, "Zmag": Zmag, "Phase": Phase}


