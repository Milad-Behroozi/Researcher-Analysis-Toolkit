    def add_files(self, paths: List[str]):
        added = 0
        for p in paths:
            p = os.path.abspath(p)
            if not os.path.isfile(p):
                continue
            if any(os.path.abspath(x.path) == p for x in self.files):
                continue
            try:
                df = read_table_any_delim(p)
                cols = auto_detect_columns(df)
                note = ""
                if cols["E"] is None:
                    note = "Potential column not detected (choose manually)."
                lf = LoadedFile(path=p, df_raw=df, cols=cols, note=note)
                self.files.append(lf)
                added += 1
            except Exception as e:
                QtWidgets.QMessageBox.warning(self, "Read error", f"Failed to load:\n{p}\n\n{e}")
        if added:
            self.loaded_index = 0 if self.loaded_index < 0 else self.loaded_index
        self.refresh_ui()

