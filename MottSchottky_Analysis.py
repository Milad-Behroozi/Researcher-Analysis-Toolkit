# -----------------------------
# Capacitance from EIS using admittance
# -----------------------------
def capacitance_from_eis(Zre: np.ndarray, Zim: np.ndarray, freq_hz: float) -> np.ndarray:
    """
    Z = Zre + j Zim
    Y = 1/Z = G + jB
    C = B / ω
    """
    omega = 2 * np.pi * float(freq_hz)
    Z = Zre + 1j * Zim
    # prevent division by zero
    Z = np.where(np.abs(Z) < 1e-30, 1e-30 + 0j, Z)
    Y = 1.0 / Z
    B = np.imag(Y)
    C = B / omega
    return C


# -----------------------------
# Scaling for publication-style axis
# -----------------------------
def choose_scale_exponent(y: np.ndarray) -> int:
    y = np.asarray(y, dtype=float)
    y = y[np.isfinite(y) & (y > 0)]
    if y.size == 0:
        return 0
    med = np.median(y)
    exp = int(math.floor(math.log10(med))) if med > 0 else 0
    # Adjust to keep median_scaled in ~[0.3, 3]
    scaled = med / (10 ** exp) if exp != 0 else med
    if scaled < 0.3:
        exp -= 1
    elif scaled > 3.0:
        exp += 0
    # Prefer "paper-looking" exponents: round to nearest multiple of 1 (keep as is),
    # but optionally snap to 3-multiples for very large numbers:
    if abs(exp) >= 6:
        exp = int(round(exp / 3.0) * 3)
    return exp


# -----------------------------
# Linear segments detection
# -----------------------------
def linear_fit(x: np.ndarray, y: np.ndarray) -> Tuple[float, float, float]:
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    A = np.vstack([x, np.ones_like(x)]).T
    m, b = np.linalg.lstsq(A, y, rcond=None)[0]
    yhat = m * x + b
    ss_res = np.sum((y - yhat) ** 2)
    ss_tot = np.sum((y - np.mean(y)) ** 2) + 1e-30
    r2 = 1 - ss_res / ss_tot
    return float(m), float(b), float(r2)


def regression_efb_uncertainty(x: np.ndarray, y: np.ndarray, m: float, b: float) -> float:
    """Return 1-sigma uncertainty of x-intercept (Efb) for y = m x + b.

    Uses standard OLS formulas (assuming homoscedastic residuals).
    If not enough points or degenerate x, returns NaN.
    """
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    mask = np.isfinite(x) & np.isfinite(y)
    x = x[mask]
    y = y[mask]
    n = int(x.size)
    if n < 3 or not np.isfinite(m) or not np.isfinite(b) or abs(m) < 1e-30:
        return float("nan")

    yhat = m * x + b
    resid = y - yhat
    dof = n - 2
    if dof <= 0:
        return float("nan")

    s2 = float(np.sum(resid**2)) / float(dof)  # residual variance
    xbar = float(np.mean(x))
    Sxx = float(np.sum((x - xbar) ** 2))
    if Sxx <= 1e-30:
        return float("nan")

    var_m = s2 / Sxx
    var_b = s2 * (1.0 / n + (xbar * xbar) / Sxx)
    cov_mb = -xbar * s2 / Sxx

    # x0 = -b/m
    dxb = -1.0 / m
    dxm = b / (m * m)
    var_x0 = (dxb * dxb) * var_b + (dxm * dxm) * var_m + 2.0 * dxb * dxm * cov_mb
    if var_x0 < 0:
        # numerical guard
        var_x0 = 0.0
    return float(math.sqrt(var_x0))


def detect_linear_segments(
    x: np.ndarray,
    y: np.ndarray,
    win: int = 25,
    r2_min: float = 0.985,
    min_len: int = 35,
) -> List[Tuple[int, int, float, float, float]]:
    """
    Sliding-window local linearity; merges contiguous linear regions.
    Returns list of (start, end, m, b, r2) for each merged segment fit.
    """
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    n = len(x)
    if n < max(10, min_len):
        return []

    win = int(max(9, win))
    if win >= n:
        win = max(9, n // 2)

    half = win // 2
    good = np.zeros(n, dtype=bool)

    for i in range(half, n - half):
        xs = x[i - half:i + half + 1]
        ys = y[i - half:i + half + 1]
        if np.any(~np.isfinite(xs)) or np.any(~np.isfinite(ys)):
            continue
        m, b, r2 = linear_fit(xs, ys)
        if r2 >= r2_min and np.isfinite(m) and abs(m) > 1e-30:
            good[i] = True

    segs = []
    i = 0
    while i < n:
        if not good[i]:
            i += 1
            continue
        j = i
        while j < n and good[j]:
            j += 1
        start = max(0, i - half)
        end = min(n, j + half)
        if end - start >= min_len:
            segs.append((start, end))
        i = j

    if not segs:
        return []

    segs.sort()
    merged = [segs[0]]
    for s, e in segs[1:]:
        ps, pe = merged[-1]
        if s <= pe:
            merged[-1] = (ps, max(pe, e))
        else:
            merged.append((s, e))

    out = []
    for s, e in merged:
        xs = x[s:e]
        ys = y[s:e]
        mask = np.isfinite(xs) & np.isfinite(ys)
        xs, ys = xs[mask], ys[mask]
        if xs.size < min_len:
            continue
        m, b, r2 = linear_fit(xs, ys)
        if r2 >= r2_min and abs(m) > 1e-30:
            out.append((s, e, m, b, r2))
    return out


