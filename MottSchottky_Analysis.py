    def redraw_selected_spans(self):
        """Re-draw shaded phase spans and their labels after axes are cleared."""
        if not getattr(self, "selected_ranges", None):
            return

        # Remove any stale artists
        for rr in self.selected_ranges:
            try:
                if isinstance(rr, dict) and rr.get("patch") is not None:
                    rr["patch"].remove()
            except Exception:
                pass
            try:
                if isinstance(rr, dict) and rr.get("label") is not None:
                    rr["label"].remove()
            except Exception:
                pass
            if isinstance(rr, dict):
                rr["patch"] = None
                rr["label"] = None

        # Draw spans and labels
        y0, y1 = self.canvas.ax.get_ylim()
        y_text = y1 - 0.05 * (y1 - y0)
        for i, rr in enumerate(self.selected_ranges, start=1):
            # support both dict and (xmin,xmax) tuples
            if isinstance(rr, dict):
                xmin, xmax = float(rr.get("xmin", 0.0)), float(rr.get("xmax", 0.0))
                color = rr.get("color", None)
            else:
                xmin, xmax = float(rr[0]), float(rr[1])
                color = None

            if xmax < xmin:
                xmin, xmax = xmax, xmin

            try:
                patch = self.canvas.ax.axvspan(xmin, xmax, alpha=0.20, color=color)
            except Exception:
                patch = None

            try:
                xmid = 0.5 * (xmin + xmax)
                label = self.canvas.ax.text(xmid, y_text, f"Phase {i}", fontsize=9, ha="center", va="top")
            except Exception:
                label = None

            if isinstance(rr, dict):
                rr["patch"] = patch
                rr["label"] = label
