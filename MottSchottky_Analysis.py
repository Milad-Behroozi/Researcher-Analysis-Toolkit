        for rr in getattr(self, "selected_ranges", []):
            try:
                if rr.get("patch") is not None:
                    rr["patch"].remove()
            except Exception:
                pass
            try:
                if rr.get("label") is not None:
                    rr["label"].remove()
            except Exception:
                pass
        self.selected_ranges = []
        self.update_ranges_label()
        self.canvas.draw_idle()
